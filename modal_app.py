"""Modal deployment for the TribeV2 ad-scoring API.

Serves a full FastAPI application on a GPU-backed Modal container.

Two interaction modes:
  POST /analyze  — ONE ad, scored against the historical average
  POST /compare  — TWO ads, scored head-to-head (A/B test)

Other endpoints:
  POST /interpret — (stub) LLM interpretation of results
  GET  /health    — health check
  GET  /docs      — Swagger UI (auto-generated by FastAPI)

Setup (one-time):
  1. pip install modal
  2. modal setup
  3. modal secret create huggingface-secret HUGGING_FACE_HUB_TOKEN=hf_...
  4. modal deploy modal_app.py          # deploy to cloud
     OR  modal serve modal_app.py       # hot-reload dev server
"""

import os
from pathlib import Path
from typing import Annotated, List

import modal

# ---------------------------------------------------------------------------
# Modal app + image
# ---------------------------------------------------------------------------

app = modal.App("tribev2-ad-scorer")

image = (
    modal.Image.debian_slim(python_version="3.11")
    .apt_install(["ffmpeg", "git"])
    .pip_install(["uv"])
    .run_commands(
        "uv pip install --system "
        "'tribev2[training] @ git+https://github.com/facebookresearch/tribev2.git'"
    )
    .run_commands("uv pip install --system 'numpy<2.1'")
    # FastAPI + observability deps (served inside the container)
    .pip_install([
        "fastapi[standard]>=0.115",
        "python-multipart>=0.0.18",
        "logfire[fastapi]",
    ])
    # Copy our app code into the image
    .add_local_dir("app", remote_path="/root/app")
)

# ---------------------------------------------------------------------------
# Persistent volumes
# ---------------------------------------------------------------------------

hf_cache_vol = modal.Volume.from_name("tribev2-hf-cache", create_if_missing=True)
feature_cache_vol = modal.Volume.from_name("tribev2-feature-cache", create_if_missing=True)

HF_CACHE_DIR = "/hf-cache"
FEATURE_CACHE_DIR = "/feature-cache"
XP_FOLDER = f"{FEATURE_CACHE_DIR}/xp"

# ---------------------------------------------------------------------------
# FastAPI app (defined at module level so Modal can serialise it)
# ---------------------------------------------------------------------------

def _configure_logfire() -> bool:
    """Initialise Logfire if LOGFIRE_TOKEN is set.  Returns True if active."""
    token = os.environ.get("LOGFIRE_TOKEN")
    if not token:
        return False
    try:
        import logfire
        logfire.configure(token=token)
        logfire.instrument_pydantic()
        return True
    except Exception:
        return False


def create_fastapi_app():
    """Build the FastAPI application.

    Called inside the Modal container where tribev2 + torch are available.
    Imports are lazy so the module can be parsed on the host.
    """
    import traceback

    from fastapi import FastAPI, File, Form, HTTPException, Request, UploadFile
    from fastapi.responses import HTMLResponse, JSONResponse

    # ── Logfire — must run before FastAPI app is created ──────────────
    logfire_active = _configure_logfire()

    api = FastAPI(
        title="TribeV2 Ad Scorer",
        description=(
            "Neuro-marketing ad analysis powered by TribeV2 brain encoding.\n\n"
            "**Two modes:**\n"
            "- `POST /analyze` — Upload ONE ad, scored against the historical "
            "average (percentile, z-score, verdict)\n"
            "- `POST /compare` — Upload TWO ads for head-to-head A/B testing "
            "(P(A>B), ROI deltas, winner + confidence)"
        ),
        version="0.4.0",
    )

    # ── Logfire FastAPI instrumentation ───────────────────────────────
    if logfire_active:
        import logfire
        logfire.instrument_fastapi(api)

    # ── CORS + error-catching middleware ─────────────────────────────
    CORS_HEADERS = {
        "access-control-allow-origin": "*",
        "access-control-allow-methods": "*",
        "access-control-allow-headers": "*",
        "access-control-expose-headers": "*",
    }

    @api.middleware("http")
    async def cors_and_errors(request: Request, call_next):
        # Handle preflight OPTIONS
        if request.method == "OPTIONS":
            return JSONResponse(content={"ok": True}, headers=CORS_HEADERS)

        try:
            response = await call_next(request)
        except Exception as exc:
            tb = traceback.format_exception(type(exc), exc, exc.__traceback__)
            response = JSONResponse(
                status_code=500,
                content={
                    "error": str(exc),
                    "type": type(exc).__name__,
                    "traceback": tb,
                },
            )

        # Add CORS headers to every response
        for k, v in CORS_HEADERS.items():
            response.headers[k] = v
        return response

    # state: model is injected by TribeApp.startup()
    api.state.model = None

    # ── routes ────────────────────────────────────────────────────────

    @api.get("/", response_class=HTMLResponse)
    async def root():
        """Serve the test UI — same origin as API, no CORS issues."""
        ui_path = Path("/root/app/static/test_ui.html")
        if ui_path.exists():
            return HTMLResponse(content=ui_path.read_text())
        return HTMLResponse(content="<h1>TribeV2 Ad Scorer</h1><p><a href='/docs'>API Docs</a></p>")

    @api.get("/info")
    async def info():
        return {
            "service": "tribev2-ad-scorer",
            "ui": "/",
            "docs": "/docs",
            "health": "/health",
            "modes": {
                "/analyze": "ONE ad vs historical baseline",
                "/compare": "TWO ads head-to-head A/B test",
            },
        }

    @api.get("/health")
    async def health():
        import torch
        gpu = torch.cuda.get_device_name(0) if torch.cuda.is_available() else "none"
        return {
            "status": "ok",
            "service": "tribev2-ad-scorer",
            "gpu": gpu,
            "model_loaded": api.state.model is not None,
        }

    # ── Mode 1: Single ad vs historical baseline ─────────────────────

    @api.post("/analyze")
    async def analyze(
        file: Annotated[UploadFile, File(description="Ad file (video/audio/image/text)")],
        modality: Annotated[str, Form(description="video, audio, image, or text")] = "video",
        ad_id: Annotated[str, Form(description="Label for this ad")] = "ad_001",
    ):
        """Score ONE ad against the historical average."""
        import asyncio
        from app.services.pipeline import analyze_single

        file_bytes = await file.read()
        filename = file.filename or f"upload.{modality}"
        return await asyncio.to_thread(
            analyze_single,
            model=api.state.model,
            file_bytes=file_bytes,
            filename=filename,
            modality=modality,
            ad_id=ad_id,
        )

    # ── Mode 2: Two ads head-to-head A/B test ────────────────────────

    @api.post("/compare")
    async def compare(
        file_a: Annotated[UploadFile, File(description="Ad A file")],
        file_b: Annotated[UploadFile, File(description="Ad B file")],
        modality: Annotated[str, Form(description="video, audio, image, or text")] = "video",
        ad_a_id: Annotated[str, Form(description="Label for Ad A")] = "ad_A",
        ad_b_id: Annotated[str, Form(description="Label for Ad B")] = "ad_B",
    ):
        """A/B test TWO ads head-to-head."""
        import asyncio
        from app.services.pipeline import compare_two

        bytes_a = await file_a.read()
        bytes_b = await file_b.read()

        return await asyncio.to_thread(
            compare_two,
            model=api.state.model,
            file_a={
                "bytes": bytes_a,
                "filename": file_a.filename or f"ad_a.{modality}",
                "modality": modality,
                "ad_id": ad_a_id,
            },
            file_b={
                "bytes": bytes_b,
                "filename": file_b.filename or f"ad_b.{modality}",
                "modality": modality,
                "ad_id": ad_b_id,
            },
        )

    # ── LLM interpretation stub ──────────────────────────────────────

    @api.post("/interpret")
    async def interpret(body: dict):
        """LLM interpretation of scoring results (stub)."""
        return {
            "interpretation": (
                "LLM interpretation not yet wired. Pass the scoring JSON "
                "from /analyze or /compare to your preferred LLM."
            ),
            "input_keys": list(body.keys()),
        }

    return api


# ---------------------------------------------------------------------------
# Modal class — GPU container that serves the FastAPI app
# ---------------------------------------------------------------------------

@app.cls(
    gpu="A10G",
    image=image,
    volumes={
        HF_CACHE_DIR: hf_cache_vol,
        FEATURE_CACHE_DIR: feature_cache_vol,
    },
    secrets=[
        modal.Secret.from_name("huggingface-secret"),
        modal.Secret.from_name("logfire-secret"),
    ],
    timeout=600,
    scaledown_window=600,
)
@modal.concurrent(max_inputs=4)
class TribeApp:
    """Wraps TribeModel and serves the FastAPI app on Modal."""

    @modal.enter()
    def startup(self):
        """Load model weights into GPU on container start."""
        os.environ["HF_HOME"] = HF_CACHE_DIR
        os.environ["HF_HUB_DOWNLOAD_TIMEOUT"] = "300"
        Path(XP_FOLDER).mkdir(parents=True, exist_ok=True)

        from huggingface_hub import snapshot_download
        snapshot_download("meta-llama/Llama-3.2-3B", cache_dir=HF_CACHE_DIR)

        from tribev2 import TribeModel

        self.model = TribeModel.from_pretrained(
            "facebook/tribev2",
            cache_folder=FEATURE_CACHE_DIR,
            config_update={"infra.folder": XP_FOLDER},
        )

        # Inject the loaded model into the FastAPI app state
        self._fastapi_app = create_fastapi_app()
        self._fastapi_app.state.model = self.model

    @modal.asgi_app()
    def serve(self):
        """Return the FastAPI ASGI app for Modal to serve."""
        return self._fastapi_app


# ---------------------------------------------------------------------------
# Local entrypoint — quick sanity check
# ---------------------------------------------------------------------------

@app.local_entrypoint()
def main():
    """Run a quick smoke test.

    Usage: modal run modal_app.py
    """
    print("Smoke test: TribeV2 Ad Scorer")
    print("Deploy with: modal deploy modal_app.py")
    print("Dev server:  modal serve modal_app.py")
